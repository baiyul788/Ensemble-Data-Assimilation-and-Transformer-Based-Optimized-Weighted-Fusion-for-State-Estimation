#!/usr/bin/env python3
"""
BiLSTM实验运行脚本

运行BiLSTM模型的完整实验流程：
1. 训练BiLSTM模型
2. 评估融合效果
3. 生成结果CSV

使用方法:
    py run_bilstm_experiment.py --config baseline
    py run_bilstm_experiment.py --config sparse
"""

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

def run_cmd(cmd: list[str], desc: str = "") -> int:
    """运行命令并打印输出"""
    print(f"\n{'='*60}")
    if desc:
        print(f"[{desc}]")
    print(f"  {' '.join(cmd)}")
    print("=" * 60)
    result = subprocess.run(cmd, cwd=REPO_ROOT)
    return result.returncode

def main():
    parser = argparse.ArgumentParser(description="Run BiLSTM experiments")
    parser.add_argument(
        "--config", 
        choices=["baseline", "sparse"], 
        required=True,
        help="实验配置: baseline 或 sparse"
    )
    parser.add_argument("--epochs", type=int, default=300, help="训练轮数")
    parser.add_argument("--window", type=int, default=5, help="观测窗口大小")
    parser.add_argument("--seeds", default="0,1,2,3,4", help="随机种子列表")
    
    args = parser.parse_args()
    
    # Config parameters
    if args.config == "baseline":
        config_params = {
            "obs_dim": 9,
            "N": 20,
            "sigma_obs": 2.0,
            "sigma_model": 0.0,
            "alpha_enkf": 0.33,
            "alpha_eakf": 0.44,
        }
    else:  # sparse
        config_params = {
            "obs_dim": 6,
            "N": 10,
            "sigma_obs": 2.0,
            "sigma_model": 0.1,
            "alpha_enkf": 0.20,
            "alpha_eakf": 0.25,
        }
    
    print(f"Running BiLSTM experiment - Config: {args.config}")
    print(f"Params: {config_params}")
    
    # Step 1: Generate dataset (if needed)
    print(f"\nStep 1: Check/generate dataset")

    dataset_cmd = [
        sys.executable,
        "testing/test.py",
        "--seeds", args.seeds,
        "--obs_dim", str(config_params["obs_dim"]),
        "--N", str(config_params["N"]),
        "--sigma_obs", str(config_params["sigma_obs"]),
        "--sigma_model", str(config_params["sigma_model"]),
        "--skip_eval",
        "--tag", args.config,
    ]
    
    ret = run_cmd(dataset_cmd, "Generate dataset")
    if ret != 0:
        print("Warning: Dataset generation may have failed, but continue...")
    
    # Step 2: Train BiLSTM
    print(f"\nStep 2: Train BiLSTM model")

    # Dataset glob
    glob_pattern = f"date/dataset_*_{args.config}.npz"
    
    train_cmd = [
        sys.executable,
        "training/train_bilstm.py",
        "--glob", glob_pattern,
        "--epochs", str(args.epochs),
        "--window", str(args.window),
    ]
    
    ret = run_cmd(train_cmd, "Train BiLSTM model")
    if ret != 0:
        print("Error: BiLSTM training failed")
        return ret
    
    # Step 3: Evaluate
    print(f"\nStep 3: Evaluate BiLSTM fusion")

    eval_cmd = [
        sys.executable,
        "testing/test.py",
        "--seeds", args.seeds,
        "--obs_dim", str(config_params["obs_dim"]),
        "--N", str(config_params["N"]),
        "--sigma_obs", str(config_params["sigma_obs"]),
        "--sigma_model", str(config_params["sigma_model"]),
        "--fusion_window", str(args.window),
        "--alpha_enkf", str(config_params["alpha_enkf"]),
        "--alpha_eakf", str(config_params["alpha_eakf"]),
        "--model", "bilstm",
        "--export_csv",
        "--tag", args.config,
    ]
    
    ret = run_cmd(eval_cmd, "Evaluate BiLSTM fusion")
    if ret != 0:
        print("Error: BiLSTM evaluation failed")
        return ret
    
    # Step 4: Organize CSV
    print(f"\nStep 4: Organize result file")

    result_dir = Path("result")
    
    # Same filename slug logic as test.py
    def _slug_float(x: float) -> str:
        s = f"{float(x):g}"
        return s.replace("-", "m").replace(".", "p")
    
    # Source CSV (generated by test.py)
    if args.config == "baseline":
        src_csv = result_dir / "multiseed_summary_bilstm_w5_aEn0p33_aEa0p44.csv"
    else:  # sparse
        src_csv = result_dir / "multiseed_summary_bilstm_w5_aEn0p2_aEa0p25.csv"
    
    # Destination CSV
    alpha_enkf_str = _slug_float(config_params['alpha_enkf'])
    alpha_eakf_str = _slug_float(config_params['alpha_eakf'])
    dst_csv = result_dir / f"multiseed_summary_bilstm_w{args.window}_aEn{alpha_enkf_str}_aEa{alpha_eakf_str}.csv"
    
    try:
        if src_csv.exists():
            import shutil
            shutil.copy(str(src_csv), str(dst_csv))
            print(f"Result CSV saved: {dst_csv}")
        else:
            print(f"警告: 源CSV文件不存在: {src_csv}")
    except Exception as e:
        print(f"警告: CSV重命名失败: {e}")
    
    print(f"\n{'='*60}")
    print(f"BiLSTM实验完成 - 配置: {args.config}")
    print(f"{'='*60}")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())